package io.github.jsonsql;

import org.h2.jdbcx.JdbcDataSource;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.Statement;
import java.util.concurrent.atomic.AtomicInteger;

/** 每个用例一个独立内存库，互不干扰。 */
final class TestDb {

    private static final AtomicInteger SEQ = new AtomicInteger();

    private TestDb() {
    }

    static JdbcDataSource fresh() {
        try {
            JdbcDataSource ds = new JdbcDataSource();
            ds.setURL("jdbc:h2:mem:jsq_" + SEQ.incrementAndGet() + ";DB_CLOSE_DELAY=-1");
            ds.setUser("sa");
            try (Connection c = ds.getConnection(); Statement st = c.createStatement()) {
                st.execute("""
                        create table t_user (
                          id bigint generated by default as identity primary key,
                          user_name varchar(64),
                          age int,
                          balance decimal(12,2),
                          status varchar(8)
                        )
                        """);
                st.execute("""
                        create table t_orders (
                          id bigint generated by default as identity primary key,
                          order_no varchar(32),
                          amount decimal(12,2)
                        )
                        """);
                st.execute("""
                        create table t_dict (
                          id bigint primary key,
                          code varchar(32),
                          name varchar(64)
                        )
                        """);
            }
            try (Connection c2 = ds.getConnection(); Statement st2 = c2.createStatement()) {
                st2.execute("""
                        create table t_du (
                          id bigint generated by default as identity primary key,
                          user_name varchar(64),
                          deleted int default 0,
                          created_at timestamp,
                          updated_at timestamp,
                          created_by varchar(32),
                          updated_by varchar(32)
                        )
                        """);
            }
            return ds;
        } catch (Exception e) {
            throw new IllegalStateException("初始化测试库失败", e);
        }
    }

    static void seedUsers(JdbcDataSource ds) {
        try (Connection c = ds.getConnection();
             PreparedStatement ps = c.prepareStatement(
                     "insert into t_user (id, user_name, age, balance, status) values (?,?,?,?,?)")) {
            String[][] rows = {
                    {"1", "邱老师", "32", "1200.50", "A"},
                    {"2", "张三", "28", "300.00", "A"},
                    {"3", "李四", "17", "80.00", "B"},
                    {"4", "王五", "35", "9900.00", "A"},
            };
            for (String[] r : rows) {
                ps.setLong(1, Long.parseLong(r[0]));
                ps.setString(2, r[1]);
                ps.setInt(3, Integer.parseInt(r[2]));
                ps.setBigDecimal(4, new BigDecimal(r[3]));
                ps.setString(5, r[4]);
                ps.addBatch();
            }
            ps.executeBatch();
            // 显式指定过主键，自增序列要往后挪，避免后续 insert 撞主键
            try (Statement st = c.createStatement()) {
                st.execute("alter table t_user alter column id restart with 100");
            }
        } catch (Exception e) {
            throw new IllegalStateException("造数失败", e);
        }
    }
}
